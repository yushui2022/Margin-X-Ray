function shoppingReference(value: string): string | undefined {
  if (value === "one other shop’s price for the same item") return "另一家店铺的同款价格";
  if (value === "one other shop’s price for a similar item") return "另一家店铺相近商品的价格";
  const matched = /^(the lowest price for the same item|the median for similar listings) at (\d+) other shops$/.exec(value);
  if (matched) return "其他 " + matched[2] + " 家店铺" + (matched[1].includes("lowest") ? "的同款最低价" : "相近商品的中位价");
}

const monthLabels = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
const datePattern = /^(?:(Quote checked|Checked|Observed|Published|Price checked|Latest check) )?(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) (\d{1,2})(?:, (\d{4}))?(?:, (\d{1,2}:\d{2})\s*(AM|PM) UTC)?$/;

export function shoppingPhrase(value: string): string | undefined {
  if (Object.hasOwn(shoppingZh, value)) return shoppingZh[value];
  for (const [pattern, translated] of phrases) {
    if (pattern.test(value)) return value.replace(pattern, translated);
  }
  const date = datePattern.exec(value);
  if (date) {
    const [, prefix, month, day, year, clock, period] = date;
    return (prefix ? shoppingZh[prefix] + " " : "") + (year ? year + "年" : "") +
      (monthLabels.indexOf(month) + 1) + "月" + day + "日" + (clock ? " " + (period === "AM" ? "上午" : "下午") + clock + " UTC" : "");
  }
  const peer = /^The creator’s price (?:matches |is ([\d.]+%) (above|below) )(.+)\.$/.exec(value);
  if (peer) {
    const reference = shoppingReference(peer[3]);
    if (reference) return "博主售价" + (peer[2] ? (peer[2] === "above" ? "高于" : "低于") + reference + " " + peer[1] : "与" + reference + "相同") + "。";
  }
  const stage = /^(Profile|Posts|Shop prices|Report), (in progress|skipped|finished|pending)$/.exec(value);
  if (stage) return shoppingZh[stage[1]] + "，" + shoppingZh[stage[2]];
  // The decision builder joins a product rule and an observation into one paragraph.
  const context = /^(.+?allowance (?:in place|is \d+%|of \d+%)\.|.+?editorial allowance\.) (One other shop cannot establish a price range\.|Observed .+?\.(?:\s|$))\s*(.*)$/.exec(value);
  if (context) {
    const pieces = context.slice(1).map(text => text.trim()).filter(Boolean);
    const translated = pieces.map(text => shoppingPhrase(text));
    if (translated.every(part => part !== undefined)) return translated.join("");
  }
  const historicGrade = /^(.+\.) (\d+)\/100 on the price scale\.$/.exec(value);
  if (historicGrade) {
    const reason = shoppingPhrase(historicGrade[1]);
    if (reason) return reason + "按当时的规则得 " + historicGrade[2] + " / 100 分。";
  }
  const sourceValue = /^(Named in the post|Linked variant|Shop default|Selected variant|Shade named in the post|Store variant|Variant|Seller|Store SKU|Product barcode) · (.+)$/.exec(value);
  if (sourceValue) return shoppingZh[sourceValue[1]] + " · " + sourceValue[2];
  if (value.startsWith("· ")) {
    const part = shoppingPhrase(value.slice(2));
    if (part) return "· " + part;
  }
  if (value.includes(" · ")) {
    let changed = false;
    const parts = value.split(" · ").map(part => {
      const translated = shoppingPhrase(part);
      if (translated !== undefined) changed = true;
      return translated ?? part;
    });
    if (changed) return parts.join(" · ");
  }
  return undefined;
}
